CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE password_resets (
  token_hash CHAR(64) PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE profiles (
  id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  full_name VARCHAR(190) NOT NULL DEFAULT '',
  email VARCHAR(190),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE user_roles (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'gerente', 'vendedor')),
  UNIQUE (user_id, role)
);

CREATE TABLE brands (
  id TEXT PRIMARY KEY,
  name VARCHAR(190) NOT NULL
);

CREATE TABLE categories (
  id TEXT PRIMARY KEY,
  name VARCHAR(190) NOT NULL
);

CREATE TABLE suppliers (
  id TEXT PRIMARY KEY,
  name VARCHAR(190) NOT NULL,
  cnpj VARCHAR(30),
  contact VARCHAR(190),
  email VARCHAR(190),
  phone VARCHAR(40),
  payment_terms_days INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE customers (
  id TEXT PRIMARY KEY,
  name VARCHAR(190) NOT NULL,
  cpf VARCHAR(20),
  phone VARCHAR(40),
  email VARCHAR(190),
  address TEXT,
  birthday DATE,
  notes TEXT,
  points INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX customers_cpf_idx ON customers(cpf);

CREATE TABLE products (
  id TEXT PRIMARY KEY,
  name VARCHAR(190) NOT NULL,
  variant VARCHAR(190),
  description TEXT,
  sku VARCHAR(80),
  barcode VARCHAR(80),
  brand_id TEXT REFERENCES brands(id) ON DELETE SET NULL,
  category_id TEXT REFERENCES categories(id) ON DELETE SET NULL,
  supplier_id TEXT REFERENCES suppliers(id) ON DELETE SET NULL,
  unit VARCHAR(20) NOT NULL DEFAULT 'un',
  cost_price NUMERIC(12,2) NOT NULL DEFAULT 0,
  sale_price NUMERIC(12,2) NOT NULL DEFAULT 0,
  stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  min_stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  image_url TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX products_name_idx ON products(name);
CREATE INDEX products_barcode_idx ON products(barcode);
CREATE INDEX products_sku_idx ON products(sku);

CREATE TABLE stock_batches (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id),
  lot VARCHAR(80),
  expires_at DATE,
  quantity NUMERIC(12,3) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX stock_batches_product_idx ON stock_batches(product_id);

CREATE TABLE cash_registers (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  status VARCHAR(20) NOT NULL DEFAULT 'aberto',
  opening_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  expected_amount NUMERIC(12,2),
  counted_amount NUMERIC(12,2),
  notes TEXT,
  opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ
);
CREATE INDEX cash_registers_user_status_idx ON cash_registers(user_id, status);

CREATE TABLE cash_movements (
  id TEXT PRIMARY KEY,
  register_id TEXT NOT NULL REFERENCES cash_registers(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  type VARCHAR(20) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  reason VARCHAR(255) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX cash_movements_register_idx ON cash_movements(register_id);

CREATE TABLE sales (
  id TEXT PRIMARY KEY,
  number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  register_id TEXT REFERENCES cash_registers(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  customer_id TEXT REFERENCES customers(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'concluida',
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  change_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  cancel_reason TEXT,
  canceled_at TIMESTAMPTZ,
  canceled_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX sales_register_idx ON sales(register_id);
CREATE INDEX sales_created_idx ON sales(created_at);

CREATE TABLE sale_items (
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES sales(id),
  product_id TEXT NOT NULL REFERENCES products(id),
  name VARCHAR(255) NOT NULL,
  quantity NUMERIC(12,3) NOT NULL,
  unit_price NUMERIC(12,2) NOT NULL,
  unit_cost NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL
);
CREATE INDEX sale_items_sale_idx ON sale_items(sale_id);

CREATE TABLE sale_payments (
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES sales(id),
  method VARCHAR(20) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  installments INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX sale_payments_sale_idx ON sale_payments(sale_id);

CREATE TABLE customer_credit_payments (
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES sales(id),
  customer_id TEXT NOT NULL REFERENCES customers(id),
  register_id TEXT NOT NULL REFERENCES cash_registers(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  amount NUMERIC(12,2) NOT NULL,
  method VARCHAR(20) NOT NULL,
  notes VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX credit_payments_sale_idx ON customer_credit_payments(sale_id);
CREATE INDEX credit_payments_customer_idx ON customer_credit_payments(customer_id, created_at);
CREATE INDEX credit_payments_register_idx ON customer_credit_payments(register_id);

CREATE TABLE stock_movements (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id),
  type VARCHAR(20) NOT NULL,
  quantity NUMERIC(12,3) NOT NULL,
  reason VARCHAR(255),
  invoice_number VARCHAR(80),
  supplier_id TEXT REFERENCES suppliers(id) ON DELETE SET NULL,
  unit_cost NUMERIC(12,2),
  sale_id TEXT REFERENCES sales(id) ON DELETE SET NULL,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX stock_movements_product_idx ON stock_movements(product_id);
CREATE INDEX stock_movements_created_idx ON stock_movements(created_at);

CREATE TABLE settings (
  id INTEGER PRIMARY KEY,
  store_name VARCHAR(190) NOT NULL DEFAULT 'CMD Cosméticos',
  cnpj VARCHAR(30),
  address TEXT,
  phone VARCHAR(40),
  receipt_footer TEXT,
  block_no_stock BOOLEAN NOT NULL DEFAULT TRUE,
  default_min_stock NUMERIC(12,3) DEFAULT 5,
  points_per_real NUMERIC(10,3) NOT NULL DEFAULT 1
);

CREATE TABLE audit_logs (
  id TEXT PRIMARY KEY,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(80) NOT NULL,
  entity VARCHAR(80),
  entity_id VARCHAR(80),
  details JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE cancel_authorization (
  id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  password_hash VARCHAR(255) NOT NULL,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ,
  updated_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

